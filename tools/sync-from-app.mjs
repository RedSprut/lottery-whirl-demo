#!/usr/bin/env node
/**
 * Refresh the demo's vendored data from a local checkout of the main Lotto Simulator app.
 *
 *   node tools/sync-from-app.mjs /path/to/loto-simulator
 *
 * Writes three files and nothing else:
 *   vendor/registry.js     ← demo-drum/src/registry.js (lottery rules + fallback palette), verbatim
 *   vendor/pool-labels.js  ← only the pool.* label strings of demo-drum/src/i18n/strings.js
 *   vendor/palette.json    ← only the per-game colour tokens lifted from index.html
 *                            (LOTTERY_APP_KEYS, [data-ball-game="…"]{…}, .hball.superstar{…})
 *
 * The app's index.html itself is never copied: the demo needs its colours, not its code.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { extractFromIndexHtml } from '../themes.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../vendor');
const app = process.argv[2];
if (!app) { console.error('usage: node tools/sync-from-app.mjs /path/to/loto-simulator'); process.exit(2); }

await fs.copyFile(path.join(app, 'demo-drum/src/registry.js'), path.join(OUT, 'registry.js'));

const { DRUM_STRINGS } = await import(pathToFileURL(path.join(app, 'demo-drum/src/i18n/strings.js')).href);
const labels = Object.fromEntries(Object.entries(DRUM_STRINGS).filter(([k]) => k.startsWith('pool.')));
await fs.writeFile(path.join(OUT, 'pool-labels.js'),
  `/** Pool labels from demo-drum/src/i18n/strings.js (generated by tools/sync-from-app.mjs). */\n` +
  `export const DRUM_STRINGS = ${JSON.stringify(labels, null, 2)};\n`);

const parsed = extractFromIndexHtml(await fs.readFile(path.join(app, 'index.html'), 'utf8'));
if (!Object.keys(parsed.appKeys).length || !parsed.superstar) throw new Error('index.html: palette tokens not found');
await fs.writeFile(path.join(OUT, 'palette.json'), `${JSON.stringify(parsed, null, 2)}\n`);

console.log(`synced: ${Object.keys(labels).length} pool labels, ${Object.keys(parsed.tokensByAppKey).length} palettes`);
